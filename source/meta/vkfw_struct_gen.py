from __future__ import annotations  # Note: allows "str | None" hints on Python < 3.10

import os
import sys
import xml.etree.ElementTree as ET

# Generates 'vkfw_struct_traits.h' from the Vulkan registry (vk.xml):
#   StructType<T>::value          - sType of a Vulkan structure
#   StructExtends<T, Base>::value - true if T may be chained into Base's pNext ('structextends' in vk.xml)
# Each specialization is guarded by the macros of the core versions/extensions that declare the types,
# so the header compiles with older SDK headers and without platform-specific headers.
#
# Usage: python vkfw_struct_gen.py [path/to/vk.xml] [path/to/vkfw_struct_traits.h]
#   vk.xml is searched in $VULKAN_SDK (or $VK_SDK_PATH)/share/vulkan/registry if not passed.


vkfw_traits_beg: str =\
"""#ifndef SVKFW_VKFW_STRUCT_TRAITS_H
#define SVKFW_VKFW_STRUCT_TRAITS_H

// Note: generated by 'source/meta/vkfw_struct_gen.py' from vk.xml (header version {header_version}), do not edit by hand


namespace Simple {{
    namespace VKFW {{
        // Note: defined only for structures with 'sType'
        template <typename T>
        struct StructType;

        template <typename T, typename Base>
        struct StructExtends {{ static const bool value = false; }};
"""

vkfw_traits_end: str =\
"""    }; // VKFW END
}; // Simple END

#endif"""


def isVulkanApi(api: str | None) -> bool:
    return api is None or "vulkan" in api.split(",")


def loadRegistry(vk_xml_path: str):
    root = ET.parse(vk_xml_path).getroot()

    header_version = "?"
    for t in root.find("types"):
        name = t.find("name")
        if t.get("category") == "define" and name is not None and name.text == "VK_HEADER_VERSION" and isVulkanApi(t.get("api")):
            header_version = (name.tail or "").strip()

    # Structures with sType (aliases are typedefs of the same type, so they get no own specialization)
    stypes: dict[str, str] = {}
    extends: dict[str, list[str]] = {}
    for t in root.find("types"):
        if t.get("category") != "struct" or t.get("alias") is not None or not isVulkanApi(t.get("api")):
            continue
        name = t.get("name")
        for m in t.findall("member"):
            m_name = m.find("name")
            if m_name is not None and m_name.text == "sType" and m.get("values") and isVulkanApi(m.get("api")):
                stypes[name] = m.get("values").split(",")[0]
                break
        if name in stypes and t.get("structextends"):
            extends[name] = t.get("structextends").split(",")

    # Which core versions/extensions declare each type
    providers: dict[str, set[str]] = {}
    # Extra macros that guard sType values ('protect' in vk.xml, e.g. VK_ENABLE_BETA_EXTENSIONS for provisional values)
    stype_protect: dict[str, str] = {}
    def addRequires(owner, owner_name: str) -> None:
        for req in owner.findall("require"):
            if not isVulkanApi(req.get("api")): continue
            for rt in req.findall("type"):
                providers.setdefault(rt.get("name"), set()).add(owner_name)
            for re_ in req.findall("enum"):
                if re_.get("extends") == "VkStructureType" and re_.get("protect"):
                    stype_protect[re_.get("name")] = re_.get("protect")

    for feature in root.findall("feature"):
        if isVulkanApi(feature.get("api")):
            addRequires(feature, feature.get("name"))
    for ext in root.find("extensions"):
        if "vulkan" in (ext.get("supported") or "").split(","):
            addRequires(ext, ext.get("name"))

    return header_version, stypes, extends, providers, stype_protect


def guardOf(type_name: str, providers: dict[str, set[str]]) -> str:
    owners = providers[type_name]
    if "VK_VERSION_1_0" in owners:
        return ""
    return " || ".join(f"defined({o})" for o in sorted(owners))


def joinGuards(guards: list[str]) -> str:
    guards = [g for g in guards if g]
    if len(guards) == 1: return guards[0]
    return " && ".join(f"({g})" for g in guards)


def generate(vk_xml_path: str, out_path: str) -> None:
    header_version, stypes, extends, providers, stype_protect = loadRegistry(vk_xml_path)
    # Note: types required only by Vulkan SC (or by nothing) are not declared in the Vulkan headers
    stypes  = { n: v for n, v in stypes.items() if n in providers }
    extends = { n: v for n, v in extends.items() if n in stypes }

    # Group specializations by their guard to keep the number of #if blocks small
    groups: dict[str, list[str]] = {}
    for name in sorted(stypes):
        guard = guardOf(name, providers)
        if stypes[name] in stype_protect:
            guard = joinGuards([guard, f"defined({stype_protect[stypes[name]]})"])
        groups.setdefault(guard, []).append(
            f"        template <> struct StructType<{name}> {{ static const VkStructureType value = {stypes[name]}; }};")

    ext_groups: dict[str, list[str]] = {}
    for name in sorted(extends):
        for base in extends[name]:
            if base not in stypes: continue
            guard = joinGuards([guardOf(name, providers), guardOf(base, providers)])
            ext_groups.setdefault(guard, []).append(
                f"        template <> struct StructExtends<{name}, {base}> {{ static const bool value = true; }};")

    lines: list[str] = [vkfw_traits_beg.format(header_version=header_version)]
    for title, grouped in (("StructType", groups), ("StructExtends", ext_groups)):
        lines.append(f"\n    // {title}\n")
        for guard in sorted(grouped, key=lambda g: (g != "", g)):
            if guard: lines.append(f"#if {guard}")
            lines.extend(grouped[guard])
            if guard: lines.append("#endif")
    lines.append(vkfw_traits_end)

    with open(out_path, "w", newline="\n") as out_f:
        out_f.write("\n".join(lines))
    print(f"Generated {len(stypes)} StructType and {sum(len(v) for v in ext_groups.values())} StructExtends specializations: '{out_path}'")


def findRegistry() -> str | None:
    sdk = os.environ.get("VULKAN_SDK", os.environ.get("VK_SDK_PATH", None))
    candidates = []
    if sdk is not None:
        candidates.append(os.path.join(sdk, "share", "vulkan", "registry", "vk.xml"))
    candidates.append("/usr/share/vulkan/registry/vk.xml")
    for c in candidates:
        if os.path.isfile(c): return c
    return None


if __name__ == "__main__":
    vk_xml = sys.argv[1] if len(sys.argv) > 1 else findRegistry()
    if vk_xml is None or not os.path.isfile(vk_xml):
        print("Error: couldn't find vk.xml, pass its path as the first argument")
        exit(-1)
    print(f"Found Vulkan registry at: '{vk_xml}'")

    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "include", "interface", "vkfw_struct_traits.h")
    generate(vk_xml, os.path.normpath(out))
