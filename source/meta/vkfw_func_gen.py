from __future__ import annotations  # Note: allows "str | None" hints on Python < 3.10

import os
import re
import sys
import xml.etree.ElementTree as ET

# Generates 'vkfw_func.h' (namespace VKFW::Func) with one thin inline wrapper per Vulkan command:
#   - the name is the command name without 'vk', parameters keep their order;
#   - VkResult with only VK_SUCCESS is checked by VKFW_CHECK (throws), other VkResults are returned (errors throw);
#   - a const array with a count parameter becomes Span<T>, the count is taken from it;
#   - "count + array" enumeration (vkEnumerate*, vkGet*s) returns std::vector, VK_INCOMPLETE is handled;
#   - a single trailing output (handle, value, struct without pNext, array sized by an input) becomes the return value;
#   - trailing optional pointers/handles/arrays get default values.
# Commands are taken from volk.h (with volk's #if guards), signatures from vk.xml.
#
# Usage: python vkfw_func_gen.py [path/to/vk.xml] [path/to/volk.h] [path/to/vkfw_func.h]


vkfw_func_beg: str =\
"""#ifndef SVKFW_VKFW_FUNC_H
#define SVKFW_VKFW_FUNC_H

// Note: generated by 'source/meta/vkfw_func_gen.py' from vk.xml (header version {header_version}) and volk.h, do not edit by hand

#include <string>
#include <vector>
#include <stdexcept>

#include "vkfw_base.h"
#include "vkfw_enum.h"

// Throws if the call doesn't return VK_SUCCESS
#define VKFW_CHECK(_VKFW_CALL, _VKFW_NAME) do {{                                                                         \\
        VkResult __vkfw_res = (_VKFW_CALL);                                                                              \\
        if (__vkfw_res != VK_SUCCESS) ::Simple::VKFW::Func::throwResult_(__vkfw_res, _VKFW_NAME);                       \\
    }} while (0)


namespace Simple {{
    namespace VKFW {{
        namespace Func {{
            inline void throwResult_(VkResult _res, const char *_name) {{
                throw std::runtime_error(SVKFW_WRAPERR("VKFW::Func", "") + std::string(_name) + " failed: " + Enum::result.getName(uint32_t(_res)) + " (" + std::to_string(_res) + ")");
            }}

            // Note: Windows headers define 'CreateEvent' and 'CreateSemaphore' as macros; the wrappers with these names
            //       are declared with the macros undefined, so call them with the macros undefined as well
"""

vkfw_func_end: str =\
"""        }; // Func END
    }; // VKFW END
}; // Simple END

#endif"""

WINDOWS_MACROS = { "CreateEvent", "CreateSemaphore" }
INDENT = " " * 12


def isVulkanApi(api) -> bool:
    return api is None or "vulkan" in api.split(",")


def snake(name: str) -> str:
    res = ""
    for i, ch in enumerate(name):
        if ch.isupper() and i > 0 and (name[i-1].islower() or name[i-1].isdigit()):
            res += "_"
        res += ch.lower()
    return res


class Param:
    def __init__(self, elem):
        self.name: str = elem.find("name").text
        self.type: str = elem.find("type").text
        text = "".join(t for t in elem.itertext())
        self.decl: str = " ".join(text.split())                         # full C declaration
        name_pos = text.rfind(self.name)
        before_name = text[:name_pos]
        self.prefix: str = " ".join(before_name.split())                 # declaration before the name
        self.suffix: str = "".join(text[name_pos + len(self.name):].split())  # e.g. "[4]"
        self.ptr: int = before_name.count("*")
        self.const: bool = before_name.strip().startswith("const")
        self.fixed_array: bool = "[" in text[text.rfind(self.name):]
        self.len: str | None = elem.get("len")
        self.optional: list[str] = (elem.get("optional") or "false").split(",")
        self.cname: str = "_" + snake(re.sub(r"^p+(?=[A-Z])", "", self.name))

    def ctype(self) -> str:
        # Declaration without the name
        return self.prefix + self.suffix

    def isOptional(self) -> bool:
        return self.optional[0] == "true"


class Registry:
    def __init__(self, vk_xml_path: str):
        root = ET.parse(vk_xml_path).getroot()
        self.header_version = "?"
        self.handles: set[str] = set()
        self.with_pnext: set[str] = set()
        self.with_stype: set[str] = set()
        self.commands: dict[str, ET.Element] = {}
        self.aliases: dict[str, str] = {}

        for t in root.find("types"):
            cat, name = t.get("category"), t.get("name") or (t.find("name").text if t.find("name") is not None else None)
            if cat == "define" and name == "VK_HEADER_VERSION" and isVulkanApi(t.get("api")):
                self.header_version = (t.find("name").tail or "").strip()
            if cat == "handle": self.handles.add(name)
            if cat in ("struct", "union") and t.get("alias") is None:
                members = [m.find("name").text for m in t.findall("member") if isVulkanApi(m.get("api"))]
                if "pNext" in members: self.with_pnext.add(name)
                if "sType" in members: self.with_stype.add(name)

        for c in root.find("commands"):
            if not isVulkanApi(c.get("api")): continue
            if c.get("alias") is not None:
                self.aliases[c.get("name")] = c.get("alias")
            else:
                self.commands[c.find("proto").find("name").text] = c

    def command(self, name: str):
        while name in self.aliases: name = self.aliases[name]
        return self.commands.get(name)


def loadVolk(volk_h_path: str) -> list[tuple[str, str]]:
    # Returns (command, guard) in volk's order from the prototypes section
    res, guard, inside = [], "", False
    with open(volk_h_path) as f:
        for line in f:
            if "VOLK_GENERATE_PROTOTYPES_H" in line:
                inside = not inside
                continue
            if not inside: continue
            if line.startswith("#if "): guard = line[4:].strip()
            elif line.startswith("#endif"): guard = ""
            else:
                m = re.match(r"extern PFN_(vk\w+) \1;", line.strip())
                if m: res.append((m.group(1), guard))
    return res


def genCommand(reg: Registry, vk_name: str) -> list[str] | None:
    cmd = reg.command(vk_name)
    if cmd is None: return None

    ret_type = cmd.find("proto").find("type").text
    params = [Param(p) for p in cmd.findall("param") if isVulkanApi(p.get("api"))]
    by_name = { p.name: p for p in params }
    success = (cmd.get("successcodes") or "").split(",") if cmd.get("successcodes") else []
    single_success = ret_type == "void" or (ret_type == "VkResult" and success == ["VK_SUCCESS"])
    returns_result = ret_type == "VkResult"

    # Note: names may repeat after the 'p' prefix is dropped, fall back to the full name then
    cnames = [p.cname for p in params]
    for p in params:
        if cnames.count(p.cname) > 1: p.cname = "_" + snake(p.name)

    removed: set[str] = set()         # parameters not in the wrapper signature
    spans: dict[str, str] = {}        # array param -> count param
    out_kind, out_param, out_size = None, None, None   # 'value' | 'vector' | 'enum'

    # Enumeration: '..., T *count, E *array)' with the array sized by the count pointer
    if len(params) >= 2:
        cnt, arr = params[-2], params[-1]
        if (cnt.ptr == 1 and not cnt.const and cnt.type in ("uint32_t", "size_t") and arr.len == cnt.name and arr.ptr == 1
                and not arr.const and sum(1 for p in params if p.len == cnt.name) == 1
                and set(success) <= {"VK_SUCCESS", "VK_INCOMPLETE"}):
            out_kind, out_param = "enum", arr
            removed |= { cnt.name, arr.name }

    # Input arrays: 'const T *array' sized by an integer parameter
    for p in params:
        if p.name in removed or p.len is None or p.ptr != 1 or not p.const or p.fixed_array or p.type == "void": continue
        count = by_name.get(p.len.split(",")[0])
        if count is None or count.ptr != 0 or count.type not in ("uint32_t", "size_t", "VkDeviceSize"): continue
        spans[p.name] = count.name
    for count_name in set(spans.values()):
        users = [p for p in params if p.len and p.len.split(",")[0] == count_name]
        inputs = [p for p in users if p.name in spans]
        others = [p for p in users if p.name not in spans]
        # Note: arrays of the same count that can't be spans (e.g. outputs) keep the count only if they aren't outputs sized by it
        if any(not (o.ptr == 1 and not o.const) for o in others):
            for p in inputs: del spans[p.name]
            continue
        removed.add(count_name)

    # Single trailing output
    if out_kind is None and single_success and params:
        last = params[-1]
        is_out = last.ptr in (1, 2) and not last.const and not last.fixed_array and last.name not in spans
        if is_out and last.len is None:
            # Note: 'void **' (mapped pointer) is returned as 'void *'; structures with pNext stay pointers to allow chains
            if (last.ptr == 1 and last.type != "void" and last.type not in reg.with_pnext) or (last.ptr == 2 and last.type == "void"):
                out_kind, out_param, out_size = "value", last, None
        elif is_out and last.ptr == 1 and last.type != "void":
            if last.len in by_name and last.len in removed:
                out_kind, out_param, out_size = "vector", last, by_name[last.len]
            elif re.fullmatch(r"p\w+->\w+", last.len) and last.len.split("->")[0] in by_name:
                out_kind, out_param, out_size = "vector", last, last.len
        if out_kind is not None: removed.add(last.name)

    if out_kind is None and ret_type not in ("void", "VkResult"):
        pass  # other return types (VkBool32, VkDeviceAddress, PFN...) are returned as they are

    # Wrapper signature
    sig: list[tuple[Param, str]] = []
    for p in params:
        if p.name in removed: continue
        if p.name in spans: sig.append((p, f"Span<{p.type}> {p.cname}"))
        else:
            ctype = p.ctype()
            if p.fixed_array: sig.append((p, f"{p.prefix} {p.cname}{p.suffix}"))
            else: sig.append((p, f"{ctype} {p.cname}"))
    # Defaults for the trailing optional parameters
    decls = [s for _, s in sig]
    for i in range(len(sig) - 1, -1, -1):
        p, _ = sig[i]
        # Note: an array is optional also if its count may be 0 (e.g. 'pDescriptorCopies' of vkUpdateDescriptorSets)
        if p.name in spans and (p.isOptional() or by_name[spans[p.name]].isOptional()): decls[i] += " = {}"
        elif p.ptr >= 1 and (p.isOptional() or p.type == "VkAllocationCallbacks") and not p.fixed_array: decls[i] += " = nullptr"
        elif p.ptr == 0 and p.type in reg.handles and p.isOptional(): decls[i] += " = VK_NULL_HANDLE"
        elif p.ptr == 0 and p.type.endswith("Flags") and p.isOptional() and not p.fixed_array: decls[i] += " = 0u"
        else: break

    # Return type
    if out_kind == "value":
        elem = out_param.type + ("*" * (out_param.ptr - 1))
        res_type = elem
    elif out_kind in ("vector", "enum"):
        elem = "uint8_t" if out_param.type == "void" else out_param.type
        res_type = f"std::vector<{elem}>"
    elif returns_result and not single_success:
        res_type = "VkResult"
    elif returns_result:
        res_type = "void"
    else:
        res_type = ret_type

    name = vk_name[2:]
    body: list[str] = []

    # Span counts: the first non-optional span gives the count, the others must match or be empty if optional
    for count_name in sorted(set(spans[p] for p in spans if spans[p] in removed)):
        arrays = [p for p in params if p.name in spans and spans[p.name] == count_name]
        main = next((a for a in arrays if not a.isOptional()), arrays[0])
        count = by_name[count_name]
        body.append(f"const {count.type} __{snake(count_name)} = ({count.type}){main.cname}.size();")
        for a in arrays:
            if a is main: continue
            cond = f"{a.cname}.size() == __{snake(count_name)}" + (f" || {a.cname}.empty()" if a.isOptional() else "")
            body.append(f'SVKFW_ASSERT({cond}, std::invalid_argument, "VKFW::Func :: {name}", "\'{a.cname[1:]}\' size must match \'{main.cname[1:]}\' size");')

    def arg(p: Param) -> str:
        if p.name in spans: return f"{p.cname}.data()"
        if p.name in removed and p.name in spans.values(): return f"__{snake(p.name)}"
        if out_param is not None and p is out_param:
            return "__res.data()" if out_kind == "vector" else "&__res"
        return p.cname

    if out_kind == "enum":
        cnt = params[-2]
        init = ""
        if out_param.type in reg.with_stype:
            body.append(f"{elem} __init{{}};")
            body.append(f"__init.sType = StructType<{elem}>::value;")
            init = ", __init"
        args_head = ", ".join(arg(p) for p in params[:-2])
        pre = (args_head + ", ") if args_head else ""
        body.append(f"{cnt.type} __count = 0u;")
        body.append(f"std::vector<{elem}> __res;")
        if returns_result:
            body.append("VkResult __call_res = VK_SUCCESS;")
            body.append("do {")
            body.append(f'    VKFW_CHECK_ENUM_({vk_name}({pre}&__count, nullptr), "{vk_name}");')
            body.append("    if (__count == 0u) break;")
            body.append(f"    __res.resize(__count{init});")
            body.append(f"    __call_res = {vk_name}({pre}&__count, __res.data());")
            body.append(f'    if (__call_res < 0) throwResult_(__call_res, "{vk_name}");')
            body.append("} while (__call_res == VK_INCOMPLETE);")
        else:
            body.append(f"{vk_name}({pre}&__count, nullptr);")
            body.append(f"__res.resize(__count{init});")
            body.append(f"if (__count != 0u) {vk_name}({pre}&__count, __res.data());")
        body.append("__res.resize(__count);")
        body.append("return __res;")
    else:
        if out_kind == "value":
            init = " = VK_NULL_HANDLE" if out_param.type in reg.handles and out_param.ptr == 1 else (" = nullptr" if out_param.ptr == 2 else "{}")
            body.append(f"{res_type} __res{init};")
        elif out_kind == "vector":
            size = out_size if isinstance(out_size, str) else None
            if size is not None:
                pname = size.split("->")[0]
                size = by_name[pname].cname + "->" + size.split("->")[1]
            else:
                size = f"__{snake(out_size.name)}"
            body.append(f"{res_type} __res((size_t){size});")
        call = f"{vk_name}({', '.join(arg(p) for p in params)})"
        if returns_result and single_success:
            body.append(f'VKFW_CHECK({call}, "{vk_name}");')
        elif returns_result:
            body.append(f"VkResult __call_res = {call};")
            body.append(f'if (__call_res < 0) throwResult_(__call_res, "{vk_name}");')
            body.append("return __call_res;")
        elif ret_type != "void" and out_kind is None:
            body.append(f"return {call};")
        else:
            body.append(f"{call};")
        if out_kind is not None:
            body.append("return __res;")

    lines = [f"{INDENT}inline {res_type} {name}({', '.join(decls)}) {{"]
    lines += [INDENT + "    " + b for b in body]
    lines.append(INDENT + "}")
    if name in WINDOWS_MACROS:
        lines = [f'#pragma push_macro("{name}")', f"#undef {name}"] + lines + [f'#pragma pop_macro("{name}")']
    return lines


def generate(vk_xml_path: str, volk_h_path: str, out_path: str) -> None:
    reg = Registry(vk_xml_path)
    volk = loadVolk(volk_h_path)

    lines = [vkfw_func_beg.format(header_version=reg.header_version)]
    lines.append(INDENT + "// Note: like VKFW_CHECK, but VK_INCOMPLETE is a success")
    lines.append("#define VKFW_CHECK_ENUM_(_VKFW_CALL, _VKFW_NAME) do { VkResult __vkfw_res = (_VKFW_CALL); if (__vkfw_res < 0) throwResult_(__vkfw_res, _VKFW_NAME); } while (0)")

    count, skipped, guard = 0, [], None
    for vk_name, cmd_guard in volk:
        func = genCommand(reg, vk_name)
        if func is None:
            skipped.append(vk_name)
            continue
        if cmd_guard != guard:
            if guard: lines.append("#endif")
            lines.append("")
            if cmd_guard: lines.append(f"#if {cmd_guard}")
            guard = cmd_guard
        lines.extend(func)
        count += 1
    if guard: lines.append("#endif")
    lines.append("#undef VKFW_CHECK_ENUM_")
    lines.append(vkfw_func_end)

    with open(out_path, "w", newline="\n") as out_f:
        out_f.write("\n".join(lines))
    print(f"Generated {count} wrappers: '{out_path}'")
    if skipped:
        print(f"Skipped {len(skipped)} commands that volk declares but vk.xml doesn't have (vk.xml is older than volk)")


def findSdkFile(*rel: str) -> str | None:
    sdk = os.environ.get("VULKAN_SDK", os.environ.get("VK_SDK_PATH", None))
    if sdk is not None and os.path.isfile(os.path.join(sdk, *rel)): return os.path.join(sdk, *rel)
    if os.path.isfile(os.path.join("/usr", *rel)): return os.path.join("/usr", *rel)
    return None


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    vk_xml = sys.argv[1] if len(sys.argv) > 1 else findSdkFile("share", "vulkan", "registry", "vk.xml")
    volk_h = sys.argv[2] if len(sys.argv) > 2 else os.path.normpath(os.path.join(here, "..", "..", "ext_sources", "volk", "volk.h"))
    out    = sys.argv[3] if len(sys.argv) > 3 else os.path.normpath(os.path.join(here, "..", "..", "include", "interface", "vkfw_func.h"))
    if vk_xml is None or not os.path.isfile(vk_xml):
        print("Error: couldn't find vk.xml, pass its path as the first argument")
        exit(-1)
    print(f"Found Vulkan registry at: '{vk_xml}', volk at: '{volk_h}'")
    generate(vk_xml, volk_h, out)
